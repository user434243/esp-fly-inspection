alias simtest='~/drone_ws/venv/bin/python ~/drone_ws/scripts/simtest.py'
alias simdist='~/drone_ws/venv/bin/python ~/drone_ws/scripts/simdist.py'
alias simworld='~/drone_ws/venv/bin/python ~/drone_ws/scripts/simworld.py'
