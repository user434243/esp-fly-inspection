# shortcuts used in this project (from ~/.bashrc)
export DRONE_WS=~/drone_ws
alias dws='cd $DRONE_WS'
alias venv='source $DRONE_WS/venv/bin/activate'
alias sim='cd $DRONE_WS/sim/CrazySim/crazyflie-firmware && bash tools/crazyflie-simulation/simulator_files/gazebo/launch/sitl_singleagent.sh -m crazyflie -x 0 -y 0'
alias fly='$DRONE_WS/venv/bin/python $DRONE_WS/scripts/fly.py'
alias simwall='cd $DRONE_WS/sim/CrazySim/crazyflie-firmware && bash tools/crazyflie-simulation/simulator_files/gazebo/launch/sitl_singleagent.sh -m crazyflie -x 0 -y 0 -w inspection_wall'
alias lab='conda activate ml && cd $DRONE_WS && jupyter lab'
alias simbridge='cd $DRONE_WS/sim/CrazySim/crazyflie-firmware && bash tools/crazyflie-simulation/simulator_files/gazebo/launch/sitl_singleagent.sh -m crazyflie -x 0 -y 0 -w bridge_pier'
alias simfull='cd $DRONE_WS/sim/CrazySim/crazyflie-firmware && bash tools/crazyflie-simulation/simulator_files/gazebo/launch/sitl_singleagent.sh -m crazyflie -x 0 -y 0 -w $(cat $HOME/drone_ws/sim/active_world 2>/dev/null || echo bridge_full)'
alias simreset='pkill -f pilot.py; pkill -f "gz sim"; pkill -f cf2; sleep 2'
alias pilot='~/drone_ws/venv/bin/python ~/drone_ws/scripts/pilot.py'
alias autopilot='~/drone_ws/venv/bin/python ~/drone_ws/scripts/autopilot.py'
alias rec='~/drone_ws/scripts/rec.sh'
